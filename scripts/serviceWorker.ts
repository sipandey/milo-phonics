import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative, resolve, sep } from 'node:path';

export interface ServiceWorkerSourceOptions {
  cacheName: string;
  precacheUrls: string[];
}

export interface ReleaseManifest {
  version: string;
  commit: string;
  channel: string;
}

function walkFiles(directory: string): string[] {
  const files: string[] = [];

  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const entryPath = join(directory, entry.name);
    if (entry.isDirectory()) {
      files.push(...walkFiles(entryPath));
    } else if (entry.isFile()) {
      files.push(entryPath);
    }
  }

  return files;
}

export function collectPrecacheUrls(distDirectory: string): string[] {
  return walkFiles(distDirectory)
    .filter((filePath) => !filePath.endsWith(`${sep}sw.js`))
    .map((filePath) => `/${relative(distDirectory, filePath).split(sep).join('/')}`)
    .sort();
}

export function createPrecacheDigest(distDirectory: string, precacheUrls: string[]): string {
  const digest = createHash('sha256');

  for (const url of precacheUrls) {
    const filePath = resolve(distDirectory, url.slice(1));
    digest.update(url);
    digest.update(readFileSync(filePath));
  }

  return digest.digest('hex').slice(0, 16);
}

function safeCachePart(value: string): string {
  return value.replace(/[^a-zA-Z0-9._-]/g, '-');
}

export function createCacheName(release: ReleaseManifest, precacheDigest: string): string {
  return `milo-precache-${safeCachePart(release.version)}-${safeCachePart(release.commit)}-${precacheDigest}`;
}

export function createServiceWorkerSource({ cacheName, precacheUrls }: ServiceWorkerSourceOptions): string {
  const serializedUrls = JSON.stringify(precacheUrls, null, 2);

  return `/* Generated by scripts/generate-service-worker.ts. */
const CACHE_NAME = ${JSON.stringify(cacheName)};
const PRECACHE_URLS = ${serializedUrls};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then((cache) => cache.addAll(PRECACHE_URLS))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((cacheNames) => Promise.all(
        cacheNames
          .filter((cacheName) => cacheName.startsWith('milo-precache-') && cacheName !== CACHE_NAME)
          .map((cacheName) => caches.delete(cacheName)),
      ))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;

  const requestUrl = new URL(request.url);
  if (requestUrl.origin !== self.location.origin) return;

  event.respondWith(
    caches.match(request).then((cachedResponse) => {
      if (cachedResponse) return cachedResponse;

      return fetch(request).catch((error) => {
        if (request.mode !== 'navigate') throw error;

        return caches.match('/index.html').then((fallbackResponse) => {
          if (fallbackResponse) return fallbackResponse;
          throw error;
        });
      });
    }),
  );
});
`;
}

export function readReleaseManifest(path: string): ReleaseManifest {
  const value = JSON.parse(readFileSync(path, 'utf8')) as unknown;
  if (typeof value !== 'object' || value === null) {
    throw new Error(`Invalid release metadata at ${path}`);
  }

  const record = value as Record<string, unknown>;
  if (
    typeof record.version !== 'string'
    || typeof record.commit !== 'string'
    || typeof record.channel !== 'string'
  ) {
    throw new Error(`Invalid release metadata at ${path}`);
  }

  return {
    version: record.version,
    commit: record.commit,
    channel: record.channel,
  };
}

export function ensureDirectoryExists(directory: string): void {
  if (!statSync(directory).isDirectory()) {
    throw new Error(`Expected directory at ${directory}`);
  }
}
